begin;

create table if not exists public.fare_areas (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

alter table public.routes
  add column if not exists fare_area_id bigint
    references public.fare_areas(id) on delete restrict;

alter table public.fare_rules
  add column if not exists fare_area_id bigint
    references public.fare_areas(id) on delete restrict;

alter table public.fare_rules
  drop constraint if exists fare_rules_variant_id_effective_from_key;

create unique index if not exists idx_fare_rules_unscoped_effective
  on public.fare_rules(variant_id, effective_from)
  where fare_area_id is null;

create unique index if not exists idx_fare_rules_area_effective
  on public.fare_rules(variant_id, fare_area_id, effective_from)
  where fare_area_id is not null;

create table if not exists public.fare_rule_distance_bands (
  id bigint generated by default as identity primary key,
  fare_rule_id bigint not null
    references public.fare_rules(id) on delete cascade,
  lower_distance_km numeric(6,2) not null
    check (lower_distance_km >= 0),
  upper_distance_km numeric(6,2),
  per_km_rate numeric(8,2) not null
    check (per_km_rate >= 0),
  created_at timestamptz not null default now(),
  unique (fare_rule_id, lower_distance_km),
  check (
    upper_distance_km is null
    or upper_distance_km > lower_distance_km
  )
);

create table if not exists public.fare_discount_rules (
  id bigint generated by default as identity primary key,
  variant_id bigint not null
    references public.transport_variants(id) on delete restrict,
  passenger_category text not null
    check (passenger_category in ('student', 'senior_citizen', 'pwd')),
  discount_percent numeric(5,2) not null
    check (discount_percent > 0 and discount_percent <= 100),
  effective_from date not null,
  effective_to date,
  source_name text not null,
  source_url text not null,
  verification_status text not null default 'unverified'
    check (
      verification_status in ('verified', 'secondary', 'unverified')
    ),
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  check (effective_to is null or effective_to > effective_from),
  unique (variant_id, passenger_category, effective_from)
);

create index if not exists idx_fare_rules_variant_area
  on public.fare_rules(variant_id, fare_area_id);
create index if not exists idx_fare_rule_bands_rule_distance
  on public.fare_rule_distance_bands(fare_rule_id, lower_distance_km);
create index if not exists idx_fare_discount_rules_variant_category_effective
  on public.fare_discount_rules(
    variant_id,
    passenger_category,
    effective_from desc
  );

alter table public.fare_areas enable row level security;
alter table public.fare_rule_distance_bands enable row level security;
alter table public.fare_discount_rules enable row level security;

drop policy if exists "Authenticated users can read fare areas"
  on public.fare_areas;
create policy "Authenticated users can read fare areas"
  on public.fare_areas for select to authenticated
  using (true);

drop policy if exists "Moderators manage fare areas"
  on public.fare_areas;
create policy "Moderators manage fare areas"
  on public.fare_areas for all to authenticated
  using (public.is_moderator())
  with check (public.is_moderator());

drop policy if exists "Authenticated users can read fare rule distance bands"
  on public.fare_rule_distance_bands;
create policy "Authenticated users can read fare rule distance bands"
  on public.fare_rule_distance_bands for select to authenticated
  using (
    public.is_moderator()
    or exists (
      select 1
      from public.fare_rules fr
      where fr.id = fare_rule_distance_bands.fare_rule_id
        and not fr.is_deleted
    )
  );

drop policy if exists "Moderators manage fare rule distance bands"
  on public.fare_rule_distance_bands;
create policy "Moderators manage fare rule distance bands"
  on public.fare_rule_distance_bands for all to authenticated
  using (public.is_moderator())
  with check (public.is_moderator());

drop policy if exists "Authenticated users can read fare discount rules"
  on public.fare_discount_rules;
create policy "Authenticated users can read fare discount rules"
  on public.fare_discount_rules for select to authenticated
  using (not is_deleted or public.is_moderator());

drop policy if exists "Moderators manage fare discount rules"
  on public.fare_discount_rules;
create policy "Moderators manage fare discount rules"
  on public.fare_discount_rules for all to authenticated
  using (public.is_moderator())
  with check (public.is_moderator());

grant select on public.fare_areas,
  public.fare_rule_distance_bands,
  public.fare_discount_rules to authenticated;
grant insert, update, delete on public.fare_areas,
  public.fare_rule_distance_bands,
  public.fare_discount_rules to authenticated;
grant usage, select on sequence public.fare_areas_id_seq,
  public.fare_rule_distance_bands_id_seq,
  public.fare_discount_rules_id_seq to authenticated;

insert into public.fare_rule_distance_bands
  (fare_rule_id, lower_distance_km, upper_distance_km, per_km_rate)
select
  fr.id,
  fr.base_distance_km,
  null,
  fr.per_km_rate
from public.fare_rules fr
where not exists (
  select 1
  from public.fare_rule_distance_bands band
  where band.fare_rule_id = fr.id
);

insert into public.fare_discount_rules
  (variant_id, passenger_category, discount_percent, effective_from,
   source_name, source_url, verification_status)
select
  tv.id,
  category.passenger_category,
  20,
  date '2026-10-27',
  category.source_name,
  category.source_url,
  'unverified'
from public.transport_variants tv
cross join (values
  ('student',
   'Republic Act No. 11314 (Student Fare Discount Act of 2019)',
   'https://www.officialgazette.gov.ph/2019/04/17/republic-act-no-11314/'),
  ('senior_citizen',
   'Republic Act No. 9994 (Expanded Senior Citizens Act of 2010)',
   'https://www.officialgazette.gov.ph/2010/02/15/republic-act-no-9994/'),
  ('pwd',
   'Republic Act No. 10754 (Expanded Benefits and Privileges of Persons with Disability)',
   'https://www.officialgazette.gov.ph/2016/03/23/republic-act-no-10754/')
) as category(passenger_category, source_name, source_url)
where tv.is_active
on conflict (variant_id, passenger_category, effective_from) do nothing;

commit;

